//   }
// 只有这里扫描命中、拼出来的文本，才会真正进到发给 AI 的 system prompt
// 里；这个文件本身只是数据源，不被调用就什么都不会发生。
//
// 刻意跟两套已有的东西完全独立、互不共用：
//   - 长RP自己的世界书（rpWorldBooks 表 + RpWorldBookManager.jsx）——
//     服务长RP子应用，不会因为这个文件而多出内容。
//   - shared-world 全局共享设定（sharedWorldService.js）——跨角色的
//     全局背景，不是"一本本带关键词的世界书"这个概念。
//
// ============================================================
// 每本书的格式：
//   { id, entries: [...] }
//   id 必须和 BUILTIN_WORLD_BOOK_METAS 里的 id 对应。
//
// 两类条目，共用同一个数组、同一套扫描机制，靠字段区分：
// ============================================================
//
// 【A】背景设定类（原有用法）：关键词命中 -> 整段注入一条固定的背景
//     事实，AI 需要"知道"这件事。
//   { keywords: [...], content: '固定注入的文本' }
//
// 【B】文案风格类（新增用法）：关键词命中 -> 从 texts 里随机挑一条当
//     "这一刻可以参考的说法"注入，不是要 AI 原样照抄，而是给它一个
//     可以模仿的语气/梗的参考范本。
//   {
//     keywords: [...],              // 触发用，命中即可能被抽中
//     emotionType: '分类标签',       // 只给你自己看，便于分类管理
//     app: ['message'],             // 适用场景；snapshot(发动态) 暂未
//                                    // 接入扫描，这里先标注，留着以后
//                                    // snapshot 那边接的时候直接复用
//                                    // 同一个 scanBuiltinWorldBook()
//     style: '适用的角色性格描述',
//     texts: ['文案1', '文案2', ...], // 命中后只抽一条，不是全部塞入
//     notes: '使用提醒，会一并注入提醒AI注意',
//   }
//
// - keywords：纯文本包含匹配，不区分大小写，不支持正则。
// - 判断是 A 类还是 B 类，看条目有没有 texts 数组：有 texts 就是 B 类
//   （文案风格），没有就按 content 走 A 类（背景设定）。
// - "每次只用一条，不要频繁复用同一条"：texts 类条目命中后，
//   scanBuiltinWorldBook 会在候选里随机抽一条；真正做到"最近用过的
//   不再抽"，需要调用方把 recentlyUsedTexts 传进来，不传的话就是纯随机。
//
// 聊天窗设置里的"内置世界书"总开关控制所有书是否参与扫描；
// 每本书各自有独立开关（存在 chat.enabledWorldBookIds 数组里）。
// 向后兼容：老数据没有 enabledWorldBookIds 时，scanBuiltinWorldBook 收到
// enabledBookIds=null 就当全部书都开启，行为和之前完全一致。

