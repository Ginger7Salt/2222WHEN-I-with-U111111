/**
 * 扫描 BUILTIN_WORLD_BOOKS，找出 scanText 里命中关键词的条目，拼成一段
 * 可以直接塞进system prompt的文本。
 *
 * - scanText：调用方负责拼好要扫描的文本（通常是最近几条消息），这个
 *   函数只管在给定文本里找关键词。
 * - 关键词匹配：纯文本包含、大小写不敏感。
 * - 所有书的条目汇总在一起按 maxEntries 总数上限截取，不是每本书各自
 *   限额——先到先得（按上面数组里书的顺序、书内条目的顺序）。
 * - 条目分两种：有 content 字段的按原样整段注入（背景设定类）；有
 *   texts 数组的则从里面随机挑一条注入，并带上 style/emotionType 作为
 *   "这是什么性质的参考"的说明，而不是要求 AI 原样照抄（文案风格类）。
 * - app 过滤：传了 app 时，texts 类条目如果没有把这个 app 包含在自己
 *   的 app 字段里，即使关键词命中也会被跳过（但不影响 content 类条目，
 *   那些不分场景）。
 * - enabledBookIds：可选，传入当前聊天开启的书的 id 数组。
 *   不传或传 null 时，当作全部书都开启（向后兼容老数据）。
 * - recentlyUsedTexts：可选，调用方传入"最近已经用过的原文"列表，
 *   texts 类条目抽选时会尽量避开这些，避免同一条文案短期内反复出现。
 *   不传就是纯随机，不保证不重复。
 * - 纯同步函数，不读任何数据库/网络——这个文件本身就是数据源。
 */
export const scanBuiltinWorldBook = (
  scanText,
  { maxEntries = 5, app = null, enabledBookIds = null, recentlyUsedTexts = [] } = {}
) => {
  const text = String(scanText || '').toLowerCase();
  if (!text) return '';

  // enabledBookIds 为 null 时不过滤（向后兼容）；
  // 为数组时只扫描 id 在其中的书。
  const shouldIncludeBook = (book) => {
    if (!enabledBookIds) return true;
    return enabledBookIds.includes(book.id);
  };

  // 背景设定类（content）和文案参考类（texts）分开计数、分开输出——
  // 前者是"AI需要知道的事实"，后者是"AI可以模仿的语气范本"，混在一起
  // 容易让 AI 把范本也当成要点对点复述的既定事实。两者各自仍然共用
  // 同一个 maxEntries 上限（这样不会因为拆成两段就变相翻倍命中数）。
  const contentBlocks = [];
  const textBlocks = [];
  let matchedCount = 0;

  for (const book of BUILTIN_WORLD_BOOKS) {
    if (!shouldIncludeBook(book)) continue;

    for (const entry of (book.entries || [])) {
      if (matchedCount >= maxEntries) break;

      const keywords = Array.isArray(entry.keywords) ? entry.keywords : [];
      const hit = keywords.some((kw) => kw && text.includes(String(kw).toLowerCase()));
      if (!hit) continue;

      if (Array.isArray(entry.texts) && entry.texts.length > 0) {
        // 文案风格类条目：先按 app 过滤，再从候选文案里随机挑一条。
        if (app && Array.isArray(entry.app) && !entry.app.includes(app)) {
          continue;
        }

        const candidates = entry.texts.filter((t) => !recentlyUsedTexts.includes(t));
        const pool = candidates.length > 0 ? candidates : entry.texts;
        const picked = pool[Math.floor(Math.random() * pool.length)];

        const label = entry.emotionType ? `【${entry.emotionType}】` : '';
        const styleNote = entry.style ? `（适用风格：${entry.style}）` : '';

        textBlocks.push(`- ${label}${styleNote}：${picked}`);
        matchedCount += 1;
      } else if (entry.content) {
        // 背景设定类条目：整段原样注入。
        contentBlocks.push(entry.content);
        matchedCount += 1;
      }
    }
    if (matchedCount >= maxEntries) break;
  }

  if (contentBlocks.length === 0 && textBlocks.length === 0) return '';

  const sections = [];

  if (contentBlocks.length > 0) {
    sections.push(contentBlocks.join('\n\n'));
  }

  if (textBlocks.length > 0) {
    sections.push(
      `【文案灵感参考——仅供风格借鉴，请结合你当前的性格、语气和与用户的关系自行改写表达，不要逐字照搬】\n${textBlocks.join('\n')}`
    );
  }

  return sections.join('\n\n');
};

