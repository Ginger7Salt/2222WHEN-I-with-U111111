// src/apps/messages/phoneScreen/phoneScreenDirective.js
//
// "角色发自己手机截图"的系统提示词说明。
//
// 跟 chatImageGen/chatImageGenDirective.js 同一个惯例：只有这个聊天窗自己
// 开启了开关（chat.phoneScreenEnabled，chats 表上新增的无索引字段，不需要
// 升级 db.version），AI 才会被告知有这个标签；没开的聊天里这段说明一个字
// 都不会出现。没有冷却/频率限制，什么时候发完全由角色自己判断。
//
// 标签格式的细节和为什么不用 JSON，见 phoneScreenSpec.js 文件头。

export const buildPhoneScreenPromptNote = (chat) => {
  if (chat?.phoneScreenEnabled !== true) return '';

  return `
【可选：发手机截图】
这个聊天窗开启了"手机截图"：你可以像真的截了一张自己手机屏幕发给对方
一样，用下面这个标签（对方只会看到一张手机截图，看不到标签原文）：
[PHONESHOT: 画面 | 手机风格 | 时间 | 电量 | 主色 | 内容]
- 用竖线 | 分隔，前五项的顺序不能变。
- 画面：lockscreen（锁屏通知栏）、browser（浏览器搜索记录）、music（音乐
  播放器）三选一，按你此刻想让对方看到什么来选。
- 手机风格：ios 或 android，按角色设定里用的手机来选。
- 时间：24小时制 HH:MM，要跟此刻对话的时间感一致。
- 电量：1到100的整数。
- 主色：一个十六进制颜色，比如 #3b4a6b。锁屏里是壁纸颜色，浏览器里是强
  调色，音乐里是封面和背景色；按角色的性格或此刻心情选，锁屏和音乐用偏
  深的颜色更好看。
- 内容（第六项）随画面不同：
  lockscreen：1到6条通知，条与条之间用 ;; 隔开；每条写成 应用名::标题::
    正文，最后还可以再加 ::时间（比如 刚刚、5分钟前）。
  browser：1到8条最近的搜索，用 ;; 隔开；每条写成 搜索词::时间（时间可
    省略）。搜索词要符合角色此刻的心思或生活，可以暴露一点小秘密。
  music：只写一首，写成 歌名::歌手::歌词::进度::状态。进度是0到100的整数，
    状态写 播放中 或 暂停。歌名和歌手可以是真实存在的，但歌词那一栏只能
    写一句你自己原创的短句来表达此刻的心情，或者留空，绝对不要抄写真实歌
    曲的歌词。
- 内容要符合角色自己的生活和人际关系，不要跟你们当前聊的内容矛盾；所有
  文字都用文字写，不要写表情符号。
- 整个标签里面不能出现右方括号 ]。
例：
[PHONESHOT: lockscreen | ios | 23:47 | 18 | #2f3b57 | 微信::妈妈::你到家了吗，记得给我回个电话 ;; 外卖::骑手已送达::您的订单已送达，祝您用餐愉快 ;; 日历::提醒::明天上午九点 项目评审会议::5分钟前]
[PHONESHOT: browser | android | 01:12 | 41 | #3b82c4 | 怎么才能不再想一个人::01:05 ;; 失眠 喝什么有用::00:48 ;; 附近还开着的甜品店]
[PHONESHOT: music | ios | 02:30 | 63 | #5b4a8a | 晴天::周杰伦::今晚的月亮好像在等谁::42::播放中]
只在你确实想让对方"看一眼你的手机"的时候用，不要每条回复都发，正常聊天
就好，你自己判断合适的时机，没有次数或冷却限制。
`;
};

export default { buildPhoneScreenPromptNote };