/** 随机从数组取一个元素 */
export function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

/**
 * 根据风格随机抽一条签文（可通过 forceRank 强制签级，用于调试）
 * @param {'omikuji'|'tarot'|'astro'} style
 * @param {string|null} forceRank
 */
export function pickEntry(style, forceRank = null) {
  const pool = style === 'omikuji' ? OMIKUJI : style === 'tarot' ? TAROT : ASTRO;
  const filtered = forceRank ? pool.filter((e) => e.rank === forceRank) : pool;
  return pick(filtered.length ? filtered : pool);
}

/**
 * 组装一条完整的抽签结果对象，存入 Dexie。
 */
export function buildResult(style, entry) {
  return {
    style,
    entry,
    rank: entry.rank,
    sec: SECTIONS[entry.rank],
    item: pick(LUCKY_ITEMS),
    color: pick(LUCKY_COLORS),
  };
}
